-- Stoltzen result archive
-- Public result data can be read by everyone.
-- Writes are reserved for server-side secret/service-role clients.

create table if not exists public.runners (
  id bigint generated by default as identity primary key,
  legacy_id bigint not null unique,
  name text not null,
  gender_class text,
  participation_count integer,
  personal_best_text text,
  personal_best_seconds integer,
  personal_best_year integer,
  latest_time_text text,
  latest_time_seconds integer,
  latest_time_year integer,
  trend text,
  club_current text,
  source_url text,
  source_fetched_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.results (
  id bigint generated by default as identity primary key,
  runner_id bigint not null references public.runners(id) on delete cascade,
  year integer not null check (year between 1979 and 2100),
  bib text,
  class_name text,
  club_original text,
  placing integer,
  time_text text,
  time_seconds integer,
  finish_time_text text,
  finish_time_seconds integer,
  source_cells jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (runner_id, year)
);

create table if not exists public.splits (
  result_id bigint primary key references public.results(id) on delete cascade,
  split_1_text text,
  split_1_seconds integer,
  split_2_text text,
  split_2_seconds integer,
  split_3_text text,
  split_3_seconds integer,
  updated_at timestamptz not null default now()
);

create index if not exists runners_name_lower_idx
  on public.runners (lower(name));

create index if not exists runners_legacy_id_idx
  on public.runners (legacy_id);

create index if not exists results_year_idx
  on public.results (year desc);

create index if not exists results_runner_year_idx
  on public.results (runner_id, year desc);

create index if not exists results_bib_idx
  on public.results (bib)
  where bib is not null;

create index if not exists results_class_idx
  on public.results (class_name)
  where class_name is not null;

create index if not exists results_club_idx
  on public.results (club_original)
  where club_original is not null;

create index if not exists results_finish_seconds_idx
  on public.results (year, finish_time_seconds)
  where finish_time_seconds is not null;

create or replace function public.set_stoltzen_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists runners_set_updated_at on public.runners;
create trigger runners_set_updated_at
before update on public.runners
for each row execute function public.set_stoltzen_updated_at();

drop trigger if exists results_set_updated_at on public.results;
create trigger results_set_updated_at
before update on public.results
for each row execute function public.set_stoltzen_updated_at();

drop trigger if exists splits_set_updated_at on public.splits;
create trigger splits_set_updated_at
before update on public.splits
for each row execute function public.set_stoltzen_updated_at();

alter table public.runners enable row level security;
alter table public.results enable row level security;
alter table public.splits enable row level security;

drop policy if exists "Public read runners" on public.runners;
create policy "Public read runners"
on public.runners
for select
to anon, authenticated
using (true);

drop policy if exists "Public read results" on public.results;
create policy "Public read results"
on public.results
for select
to anon, authenticated
using (true);

drop policy if exists "Public read splits" on public.splits;
create policy "Public read splits"
on public.splits
for select
to anon, authenticated
using (true);

grant usage on schema public to anon, authenticated;
grant select on public.runners, public.results, public.splits to anon, authenticated;
grant all on public.runners, public.results, public.splits to service_role;
grant usage, select on all sequences in schema public to service_role;

create or replace view public.result_search
with (security_invoker = true)
as
select
  r.id as result_id,
  r.year,
  r.bib,
  r.class_name,
  r.club_original,
  r.placing,
  r.finish_time_text,
  r.finish_time_seconds,
  p.id as runner_id,
  p.legacy_id,
  p.name,
  p.gender_class,
  p.personal_best_text,
  p.personal_best_year,
  p.participation_count
from public.results r
join public.runners p on p.id = r.runner_id;

grant select on public.result_search to anon, authenticated;
